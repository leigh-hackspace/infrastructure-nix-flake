//! Addressing a discovered uplink without declaring it.
//!
//! The flake used to write one `systemd.network` file per backup path, which
//! meant an interface name and a metric were facts in the configuration. Here
//! the daemon writes the files at runtime from what it found: any candidate
//! gets DHCP, the default route is the DHCP server's (never a typed gateway),
//! DNS is not taken (the router is the network's resolver), and the metric is
//! high enough that a DHCP lease never wins the route by itself.
//!
//! `05-` is deliberate: networkd takes the first matching file in lexical order,
//! so this beats the old `10-uplink` without deleting it on a running box. A
//! switched-in tree removes that file too.

use crate::config::Config;
use crate::net::IfaceInfo;
use crate::util::run;
use std::collections::HashMap;
use std::path::PathBuf;
use std::time::{Duration, Instant};

#[derive(Debug, Default)]
pub struct DhcpRuntime {
    pub last_reconfigure: HashMap<String, Instant>,
    pub last_reload: Option<Instant>,
    pub last_error: Option<String>,
}

fn safe(name: &str) -> String {
    name.chars()
        .map(|c| if c.is_ascii_alphanumeric() || c == '-' || c == '_' || c == '.' { c } else { '_' })
        .collect()
}

fn path_for(cfg: &Config, iface: &str) -> PathBuf {
    // The state-dir copy is created because `/run/systemd/network` is a shared
    // namespace and this crate does not want to claim a name it cannot clean up.
    cfg.networkd_dir().join(format!("05-wan-manager-{}.network", safe(iface)))
}

fn content(iface: &str, index: usize) -> String {
    // 2000 + index is a *label*, not a preference: discovery supplies
    // candidates sorted by name, and the daemon's own promoted route is 100.
    // Nothing here is ever selected by the kernel unless the daemon's route is
    // absent, which is exactly the "the daemon has not run yet" case.
    format!(
        "# GENERATED by wan-manager — do not edit on the box.\n\
         [Match]\nName={iface}\n\n\
         [Network]\nDHCP=ipv4\nIPv6AcceptRA=no\n\n\
         [DHCPv4]\nUseDNS=no\nUseRoutes=yes\nRouteMetric={}\n",
        2000 + index
    )
}

/// Write/refresh the per-interface DHCP files and ask networkd to read them.
pub fn ensure(cfg: &Config, ifaces: &[IfaceInfo], rt: &mut DhcpRuntime) -> Vec<String> {
    let mut actions = Vec::new();
    let dir = cfg.networkd_dir();
    let _ = std::fs::create_dir_all(&dir);
    // Clean up files for interfaces that are gone, so a re-plug cannot inherit
    // a stale metric or a stale name.
    let desired: std::collections::BTreeSet<String> = ifaces
        .iter()
        .filter(|i| !matches!(i.kind, crate::net::Kind::Tunnel))
        .map(|i| format!("05-wan-manager-{}.network", safe(&i.name)))
        .collect();
    if let Ok(rd) = std::fs::read_dir(&dir) {
        for e in rd.flatten() {
            let name = e.file_name().to_string_lossy().into_owned();
            if name.starts_with("05-wan-manager-") && !desired.contains(&name) {
                let _ = std::fs::remove_file(e.path());
                actions.push(format!("removed stale {name}"));
            }
        }
    }
    let mut changed = false;
    for (i, info) in ifaces
        .iter()
        .filter(|i| !matches!(i.kind, crate::net::Kind::Tunnel))
        .enumerate()
    {
        let path = path_for(cfg, &info.name);
        let body = content(&info.name, i);
        if crate::util::write_if_changed(&path, &body, 0o644) {
            changed = true;
            actions.push(format!("wrote {}", path.display()));
        }
    }
    if changed {
        actions.push("networkd files changed".into());
    }
    let mut published = publish(cfg, rt);
    actions.append(&mut published);
    for info in ifaces
        .iter()
        .filter(|i| !matches!(i.kind, crate::net::Kind::Tunnel))
    {
        // An interface with no lease and no address gets one reconfigure every
        // 120 s, not every tick: `networkctl reconfigure` tears the link's
        // configuration down, and doing that every 20 s to a radio that is still
        // doing DHCP is what made the handback flap. A full two minutes is long
        // enough for WPA + DHCP to finish on the crowded 2.4 GHz cell.
        if info.addresses.is_empty() {
            let due = rt
                .last_reconfigure
                .get(&info.name)
                .map(|t| t.elapsed() >= Duration::from_secs(120))
                .unwrap_or(true);
            if due {
                // A USB NIC can appear administratively down; networkd will not
                // DHCP a link nobody brought up.
                let _ = run(
                    "ip",
                    &[
                        "link".to_string(),
                        "set".to_string(),
                        "dev".to_string(),
                        info.name.clone(),
                        "up".to_string(),
                    ],
                    5,
                );
                let _ = run(
                    "networkctl",
                    &["reconfigure".to_string(), info.name.clone()],
                    10,
                );
                rt.last_reconfigure
                    .insert(info.name.clone(), Instant::now());
                actions.push(format!("reconfigured DHCP on {}", info.name));
            }
        }
    }
    actions
}

/// Export the files into networkd's own drop-in directory. The caller does this
/// after `ensure` has finished writing, because networkd cannot see a file that
/// is still being written.
pub fn publish(cfg: &Config, rt: &mut DhcpRuntime) -> Vec<String> {
    let src = cfg.networkd_dir();
    let dst = PathBuf::from("/run/systemd/network");
    let mut out = Vec::new();
    let _ = std::fs::create_dir_all(&dst);
    let Ok(rd) = std::fs::read_dir(&src) else {
        return out;
    };
    let mut changed = false;
    let mut needs_reload = false;
    let mut wanted: std::collections::BTreeSet<String> = std::collections::BTreeSet::new();
    for e in rd.flatten() {
        let name = e.file_name().to_string_lossy().into_owned();
        if !name.starts_with("05-wan-manager-") {
            continue;
        }
        wanted.insert(name.clone());
        let target = dst.join(&name);
        let body = std::fs::read_to_string(e.path()).unwrap_or_default();
        if crate::util::write_if_changed(&target, &body, 0o644) {
            changed = true;
            // Reloading networkd re-applies every link's routes, which can
            // flush a promoted default and drop a working DHCP lease. If the
            // interface already has an address, its new file can wait for the
            // next real reload (a boot, or a link with no address). The
            // handback is exactly the case where the address is already there.
            let iface = body
                .lines()
                .find_map(|l| l.strip_prefix("Name="))
                .unwrap_or("")
                .trim()
                .to_string();
            if iface.is_empty() || crate::net::ipv4_addresses(&iface).is_empty() {
                needs_reload = true;
            }
            out.push(format!("published {name}"));
        }
    }
    // Remove a file for an interface that has gone away. It would match nothing,
    // but a re-plug can inherit its metric and its name, and a stale file is a
    // fact nobody is maintaining.
    if let Ok(rd) = std::fs::read_dir(&dst) {
        for e in rd.flatten() {
            let name = e.file_name().to_string_lossy().into_owned();
            if name.starts_with("05-wan-manager-") && !wanted.contains(&name) {
                let _ = std::fs::remove_file(e.path());
                changed = true;
                out.push(format!("removed stale {name}"));
            }
        }
    }
    if changed && needs_reload {
        let _ = run("networkctl", &["reload".to_string()], 10);
        rt.last_reload = Some(Instant::now());
        out.push("networkctl reload".into());
    } else if changed {
        out.push("networkd files published; reload deferred (interfaces already addressed)".into());
    }
    out
}
