#!/usr/bin/env bash
# Generate the Rust asset module that embeds a built dist/ tree in the
# whisper-ws binary (include_bytes! + content type per path). The Rust side
# calls assets::asset("relative/path") — see src/status.rs serve_http.
#
# Usage: gen_assets.sh <dist-dir> <output.rs>
set -euo pipefail

if [ "$#" -ne 2 ]; then
  echo "usage: $0 <dist-dir> <output.rs>" >&2
  exit 2
fi

DIST="$1"
OUT="$2"
[ -d "$DIST" ] || { echo "dist dir not found: $DIST" >&2; exit 1; }
[ -f "$DIST/index.html" ] || { echo "missing $DIST/index.html — run the vite build first" >&2; exit 1; }
# include_bytes! takes literal paths, so emit the absolute dist location.
# In the Nix build this is a store path ($out/dist) — stable forever; locally
# it is web/app/dist on the dev machine (the generated file is gitignored).
DISTABS="$(cd "$DIST" && pwd)"

content_type() {
  case "$1" in
    *.html) echo "text/html; charset=utf-8" ;;
    *.js | *.mjs) echo "text/javascript; charset=utf-8" ;;
    *.css) echo "text/css; charset=utf-8" ;;
    *.wasm) echo "application/wasm" ;;
    *.onnx) echo "application/octet-stream" ;;
    *.map) echo "application/json" ;;
    *.md) echo "text/markdown; charset=utf-8" ;;
    *) echo "application/octet-stream" ;;
  esac
}

{
  echo "// GENERATED by gen_assets.sh — do not edit by hand."
  echo "//! Static web assets: the built status-page bundle (web/app) plus the"
  echo "//! vendored OpenWakeWord engine / onnxruntime-web / ONNX models, so the"
  echo "//! binary is fully self-contained (no CDN, nothing leaves the LAN)."
  echo
  echo "pub fn asset(path: &str) -> Option<(&'static [u8], &'static str)> {"
  echo "    Some(match path {"
  # index.html serves at both "" and "/"
  printf '    "" | "/" => (include_bytes!("%s/index.html"), "text/html; charset=utf-8"),\n' "$DISTABS"
  (
    cd "$DIST"
    find . -type f ! -name index.html | sed 's|^\./||' | LC_ALL=C sort
  ) | while IFS= read -r rel; do
    printf '    "%s" => (include_bytes!("%s/%s"), "%s"),\n' "$rel" "$DISTABS" "$rel" "$(content_type "$rel")"
  done
  echo "    _ => return None,"
  echo "    })"
  echo "}"
} > "$OUT"

echo "wrote $OUT"
