# CHECK — one report about one camera, run on the device by `just cam-check`
# (`cat cameras/inventory.sh | ssh root@<addr> sh -s`).  Nothing on our boxes
# interprets it: everything in here is busybox ash + busybox applets only, so
# there is no awk (cameras have none), no bash, no `rev` (absent on all three
# today, which is why an earlier version of this report printed an empty
# `free_kb` on a box that had 452 KB of it — a broken check reads as healthy).
# Every line is `key=value`; a finding is a match against a value, never prose.
#
# It never cats a credential or a binary: `/etc/wlanpass` and
# `/etc/wpa_supplicant.conf` hold the WiFi PSK, `/etc/httpd-htpasswd.user` the
# camera's own login, `/etc/sensors/*.bin` ~115 KB of vendor calibration each.
# Names, sizes and md5s only (rule 13: a transcript that holds one is a
# transcript someone keeps).  `/etc/crontabs/root` is listed by md5 rather than
# cat'd because cam7's copy carries a commented vendor example line that
# contains a Telegram bot API key — see cameras/README.md.
kv() { printf '%s=%s\n' "$1" "$2"; }
# yaml scalar: `key: value` -> value (grep/cut/tr only; `sed -n` without a
# `p` prints nothing, which is the trap this helper exists to avoid).
y() { grep "$1" "$2" 2>/dev/null | head -1 | cut -d: -f2- | tr -d ' '; }

